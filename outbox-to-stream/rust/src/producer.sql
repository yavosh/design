CREATE TABLE IF NOT EXISTS records(id TEXT PRIMARY KEY, revision INTEGER NOT NULL, status TEXT NOT NULL) STRICT;
CREATE TABLE IF NOT EXISTS outbox(
 id INTEGER PRIMARY KEY, event_id TEXT NOT NULL UNIQUE, stream TEXT NOT NULL, bytes BLOB NOT NULL,
 state TEXT NOT NULL DEFAULT 'PENDING' CHECK(state IN ('PENDING','IN_PROGRESS','GIVEN_UP','SENT')),
 due INTEGER NOT NULL DEFAULT (unixepoch()), token TEXT, attempts INTEGER NOT NULL DEFAULT 0,
 created INTEGER NOT NULL DEFAULT (unixepoch()), sent INTEGER, entry INTEGER, error TEXT
) STRICT;
CREATE INDEX IF NOT EXISTS outbox_due ON outbox(due,id) WHERE state IN ('PENDING','IN_PROGRESS');
CREATE INDEX IF NOT EXISTS outbox_sent ON outbox(sent) WHERE state='SENT';
