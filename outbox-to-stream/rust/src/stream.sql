CREATE TABLE IF NOT EXISTS entries(id INTEGER PRIMARY KEY AUTOINCREMENT, bytes BLOB NOT NULL, created INTEGER NOT NULL) STRICT;
CREATE TABLE IF NOT EXISTS retention(singleton INTEGER PRIMARY KEY CHECK(singleton=1), trimmed INTEGER NOT NULL);
INSERT OR IGNORE INTO retention VALUES(1,0);
CREATE TABLE IF NOT EXISTS groups(name TEXT PRIMARY KEY, cursor INTEGER NOT NULL) STRICT;
CREATE TABLE IF NOT EXISTS pending(
 name TEXT NOT NULL, entry INTEGER NOT NULL, owner TEXT NOT NULL, token TEXT NOT NULL,
 due INTEGER NOT NULL, failures INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(name,entry)
) STRICT;
CREATE TABLE IF NOT EXISTS dead(
 name TEXT NOT NULL, entry INTEGER NOT NULL, bytes BLOB NOT NULL, reason TEXT NOT NULL,
 created INTEGER NOT NULL, PRIMARY KEY(name,entry)
) STRICT;
