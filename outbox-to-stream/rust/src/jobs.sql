CREATE TABLE IF NOT EXISTS seen(source TEXT, event TEXT, PRIMARY KEY(source,event)) STRICT;
CREATE TABLE IF NOT EXISTS jobs(
 source TEXT NOT NULL, event TEXT NOT NULL, bytes BLOB NOT NULL,
 delivery_key TEXT NOT NULL UNIQUE DEFAULT (lower(hex(randomblob(16)))),
 state TEXT NOT NULL DEFAULT 'READY' CHECK(state IN ('READY','CLAIMED','DONE','REVIEW')),
 due INTEGER NOT NULL DEFAULT 0, token TEXT, attempts INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(source,event)
) STRICT;
CREATE INDEX IF NOT EXISTS jobs_due ON jobs(due) WHERE state IN ('READY','CLAIMED');
CREATE TABLE IF NOT EXISTS destination(singleton INTEGER PRIMARY KEY CHECK(singleton=1), url TEXT NOT NULL) STRICT;
